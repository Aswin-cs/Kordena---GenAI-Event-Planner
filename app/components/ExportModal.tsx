"use client";

import React, { useState } from "react";
import { Download, Copy, Check, Printer, FileText, X } from "lucide-react";
import { EventPlan } from "../types";

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  event: EventPlan;
}

export const ExportModal: React.FC<ExportModalProps> = ({
  isOpen,
  onClose,
  event,
}) => {
  const [copied, setCopied] = useState(false);

  if (!isOpen) return null;

  const totalSpent = event.budget.reduce((acc, b) => acc + b.spent, 0);
  const completedTasks = event.tasks.filter((t) => t.completed).length;

  const generateMarkdownSummary = () => {
    return `# ${event.title}
*${event.tagline}*
Generated by Kordena GenAI Event Planner

## Overview
- **Event Type:** ${event.eventType}
- **Date:** ${event.date}
- **Location:** ${event.location}
- **Guest Count:** ${event.guestCount}
- **Total Budget:** $${event.totalBudget.toLocaleString()} (Spent: $${totalSpent.toLocaleString()})
- **Completed Tasks:** ${completedTasks} / ${event.tasks.length}

## AI Aesthetic & Palette Architecture
${event.aiVibeSummary}
- Color Theme: Fresh Sage & Mint (Serene, Balanced & Focused)
  - Background (60%): #F4F7F5 (Subtle Sage Tint)
  - Surfaces & Cards (30%): #FFFFFF with #2D3748 (Slate Gray Text)
  - Accent (10%): #10B981 (Emerald / Mint Green)

## Budget Breakdown
${event.budget.map((b) => `- ${b.category}: $${b.spent.toLocaleString()} spent of $${b.allocated.toLocaleString()} allocated (${b.notes})`).join("\n")}

## Critical Calendar Alerts
${event.alerts.map((a) => `- [${a.completed ? "Resolved" : "Pending"}] ${a.title} (${a.date}) - ${a.description}`).join("\n")}

## Key Milestones Checklist
${event.tasks.map((t) => `- [${t.completed ? "x" : " "}] ${t.title} (${t.category} - Priority: ${t.priority})`).join("\n")}

## Day-of Operational Schedule
${event.schedule.map((s) => `- ${s.time}: ${s.title} (Lead: ${s.responsible})`).join("\n")}
`;
  };

  const handleCopy = () => {
    navigator.clipboard.writeText(generateMarkdownSummary());
    setCopied(true);
    setTimeout(() => setCopied(false), 2500);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 bg-[#2D3748]/50 backdrop-blur-xs flex items-center justify-center p-4">
      <div className="bg-[#FFFFFF] rounded-3xl max-w-2xl w-full border border-[#E2ECE5] shadow-2xl p-6 sm:p-8 space-y-5 animate-in fade-in zoom-in duration-150 max-h-[90vh] flex flex-col">
        <div className="flex items-center justify-between pb-4 border-b border-[#E2ECE5]">
          <div className="flex items-center gap-2.5">
            <div className="w-9 h-9 rounded-xl bg-[#E6F7F0] flex items-center justify-center text-[#10B981]">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-lg font-bold text-[#2D3748]">
                Export Event Blueprint
              </h3>
              <p className="text-xs text-[#718096]">
                Comprehensive executive summary for {event.title}
              </p>
            </div>
          </div>
          <button
            onClick={onClose}
            className="w-8 h-8 rounded-full bg-[#F4F7F5] text-[#718096] hover:text-[#2D3748] flex items-center justify-center font-bold"
          >
            <X className="w-4 h-4" />
          </button>
        </div>

        <div className="flex-1 overflow-y-auto p-4 rounded-2xl bg-[#F4F7F5] border border-[#E2ECE5] text-xs font-mono text-[#2D3748] whitespace-pre-wrap leading-relaxed select-all">
          {generateMarkdownSummary()}
        </div>

        <div className="flex items-center justify-between pt-2">
          <span className="text-xs text-[#718096]">
            Ready for stakeholder alignment and vendor handoff.
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={handlePrint}
              className="px-4 py-2 rounded-xl bg-[#F4F7F5] border border-[#E2ECE5] text-xs font-semibold text-[#2D3748] hover:bg-[#EBF3EE] flex items-center gap-1.5 cursor-pointer"
            >
              <Printer className="w-3.5 h-3.5 text-[#718096]" /> Print
            </button>
            <button
              onClick={handleCopy}
              className="px-4 py-2 rounded-xl bg-[#10B981] text-white text-xs font-semibold hover:bg-[#059669] flex items-center gap-1.5 cursor-pointer shadow-xs"
            >
              {copied ? <Check className="w-3.5 h-3.5" /> : <Copy className="w-3.5 h-3.5" />}
              {copied ? "Copied Brief!" : "Copy Summary"}
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
